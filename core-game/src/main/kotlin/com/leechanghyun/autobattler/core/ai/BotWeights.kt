package com.leechanghyun.autobattler.core.ai

/**
 * AI 봇 판단에 쓰는 가중치와 문턱값. 명세서 4-7, 로드맵 8단계.
 *
 * 명세서 4-7 이 준 수치는 [GOLD_RESERVE] 하나뿐이고, 나머지는 **식의 모양**만 정한다.
 * 그래서 여기 있는 값은 그 하나를 빼면 전부 임의 초기값이고 11단계 밸런스 튜닝 대상이다.
 * 한 곳에 모아 둔 이유가 그것이다. 코드 여기저기에 숫자가 흩어지면 11단계에서 무엇이
 * 튜닝 대상이고 무엇이 규칙인지 구분할 수 없다.
 *
 * **여기 있는 수를 바꾸는 것은 튜닝이지 버그 수정이 아니다.** 규칙 자체를 검사하는 테스트는
 * 이 값들에 기대지 않도록 상대 비교로 쓰여 있다.
 *
 * ### 값들 사이의 서열이 곧 명세서다
 * 명세서 4-7 은 "2성 완성 임박 시 **최우선**"이라고 못박았다. 그래서 복제본 2장일 때의
 * 스타업 항([STAR_UP_PER_COPY] x 2 = 12)이 임계값 돌파 보너스([THRESHOLD_BREAK_BONUS] = 8)보다
 * 크고, 그것이 다시 흔한 시너지 겹침(2~4점)보다 크도록 잡았다.
 * `BotScoringTest.스타업 임박이 다른 어떤 항보다 우선한다` 가 이 서열을 지킨다.
 */
object BotWeights {

    /**
     * 코스트가 레벨 적정치에서 1 멀어질 때마다 깎는 점수.
     *
     * 적정치는 상점 확률표에서 유도하므로([BotScoring.expectedCost]) 여기서 새 표를 만들지 않는다.
     */
    const val LEVEL_FITNESS_PER_COST = 1.0

    /**
     * 이미 가진 같은 유닛 1장당 점수. 명세서 4-7 "이미 보유한 동일 유닛 개수 x 스타업 임박 가중치".
     *
     * 2장을 들고 있으면 12점이 되어 다른 어떤 항보다 커진다. 명세서의 "2성 완성 임박 시 최우선"이다.
     */
    const val STAR_UP_PER_COPY = 6.0

    /** 보드에 같은 태그를 쓰는 유닛이 1종 있을 때마다 주는 점수. 계열과 직업을 따로 센다. */
    const val SYNERGY_PER_MEMBER = 1.0

    /** 우선 시너지로 고정한 태그는 겹침 점수를 이만큼 곱해 받는다. 명세서 4-7 "가중치를 높인다". */
    const val PRIORITY_TRAIT_MULTIPLIER = 2.0

    /** 임계값(2/4/6)을 새로 넘기는 유닛에게 단계 1개당 주는 보너스. 명세서 4-7 의 네 번째 항. */
    const val THRESHOLD_BREAK_BONUS = 8.0

    /**
     * 이 점수 미만이면 사지 않는다.
     *
     * 0 인 이유: 적정 코스트이고 시너지가 하나도 안 겹치는 유닛이 정확히 0점이 된다.
     * 즉 "아무 이득이 없으면 골드를 쓰지 않는다"가 기본값이고, 겹침이나 복제본이 하나라도 있으면 산다.
     */
    const val MIN_BUY_SCORE = 0.0

    /**
     * 항상 남겨 두는 골드. 명세서 4-7 "항상 최소 4골드는 남기고(이자 확보)".
     *
     * 명세서 4-1 의 이자는 10골드당 1이라 4골드로는 이자가 한 푼도 붙지 않는다.
     * 그래도 명세서가 4라고 적었으므로 그대로 따른다. 11단계 재검토 대상이다.
     */
    const val GOLD_RESERVE = 4

    /**
     * 경험치를 사고 나서도 남겨야 하는 골드.
     *
     * 명세서는 봇 레벨업을 한 글자도 정하지 않는다. 새 수를 짓는 대신 명세서 4-1 의
     * 이자 단위(10골드당 1)에서 가져왔다. 레벨업 때문에 이자 한 단계를 잃지 않게 한다.
     */
    const val LEVEL_UP_GOLD_FLOOR = 10

    /** 체력 1점의 가치. [BotScoring.power] 의 기준 단위다. */
    const val HP_PER_POWER = 1.0

    /**
     * 초당 피해 1점의 가치.
     *
     * 로스터의 체력은 수백 단위, 초당 피해는 수십 단위라 그대로 더하면 체력만 보는 식이 된다.
     * 10배를 곱해 두 축이 비슷한 크기가 되게 맞췄다. 임의값이고 11단계 조정 대상이다.
     */
    const val DPS_PER_POWER = 10.0
}
